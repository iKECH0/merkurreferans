function walk(dir) {
  let results = [];
  const list = fs.readdirSync(dir);
  list.forEach(file => {
    file = path.join(dir, file);
    const stat = fs.statSync(file);
    if (stat && stat.isDirectory()) { 
      results = results.concat(walk(file));
    } else if (file.endsWith('.js') || file.endsWith('.jsx') || file.endsWith('.css')) {
      results.push(file);
    }
  });
  return results;
}

const files = walk('./src');
let filesChanged = 0;

// Sort replacements by length descending to prevent partial match bugs!
const keys = Object.keys(replacements).sort((a, b) => b.length - a.length);

files.forEach(f => {
  let content = fs.readFileSync(f, 'utf8');
  let originalContent = content;
  
  if (content.includes('\ufffd')) {
    keys.forEach(k => {
      if (content.includes(k)) {
        content = content.split(k).join(replacements[k]);
      }
    });

    // Also replace standalone prefixes like ! -> Ç or  -> Ö
    content = content.replace(/\ufffd!/g, 'Ç');
    content = content.replace(/\ufffd /g, 'Ö ');
    content = content.replace(/\ufffdS/g, 'Ü');
    content = content.replace(/\ufffd\ufffdx/g, 'Öğ');

    if (content !== originalContent) {
      fs.writeFileSync(f, content, 'utf8');
      filesChanged++;
    }
  }
});

console.log('Fixed files count:', filesChanged);
